/**
 * Writes the Android launcher icons and the launch background into android/,
 * from the favicon.
 *
 *   node scripts/generate-android-icons.mjs          # regenerate them
 *   node scripts/generate-android-icons.mjs --check  # fail if android/ is out of date
 *
 * The artwork is the favicon's, read through the same rasteriser the browser
 * icons use (src/lib/app-icons.js), so the mark on a home screen and the mark in
 * a tab are the same shapes and cannot drift apart. A launcher crops an icon to
 * a shape of its own, so the adaptive foreground is drawn full bleed and pulled
 * inside the circle a launcher keeps, which is exactly what the maskable icon
 * does for the browser.
 *
 * The launch background the template ships is white, a flash of the wrong colour
 * in front of a game whose first screen is dark, so the window the application
 * opens on is written here as well: the application's own colour, with the mark
 * in the middle of it, so the launch leads into the screen that asks for a
 * language rather than into a blank rectangle of another colour.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FAVICON_FILE, readFaviconScene, renderIcon } from "../src/lib/app-icons.js";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const RES = path.join(ROOT, "android", "app", "src", "main", "res");
const check = process.argv.includes("--check");

/** The dark surface the installed application opens on, as its manifest says. */
const BACKGROUND = "#14100A";

// A launcher icon is 48dp and an adaptive foreground is 108dp, so the part a
// launcher crops away is still drawn rather than left blank.
const LAUNCHER = [
  ["mdpi", 48],
  ["hdpi", 72],
  ["xhdpi", 96],
  ["xxhdpi", 144],
  ["xxxhdpi", 192],
];
const FOREGROUND = [
  ["mdpi", 108],
  ["hdpi", 162],
  ["xhdpi", 216],
  ["xxhdpi", 324],
  ["xxxhdpi", 432],
];

// The mark on the launch window, at the size the language screen draws it: 96dp,
// so the mark on the splash and the mark on the screen behind it are the same
// size and sit in the same place, and the launch reads as one movement rather
// than two screens.
const SPLASH_MARK = [
  ["mdpi", 96],
  ["hdpi", 144],
  ["xhdpi", 192],
  ["xxhdpi", 288],
  ["xxxhdpi", 384],
];

const scene = readFaviconScene(readFileSync(path.join(ROOT, FAVICON_FILE), "utf8"));

/** The whole artwork, keeping the favicon's own rounded corners. */
const square = (size) => renderIcon(scene, { size, bleed: false });
/** The artwork full bleed, pulled inside the circle a launcher keeps. */
const cropped = (size) => renderIcon(scene, { size, bleed: true, safe: true });

const GENERATED = "Generated by scripts/generate-android-icons.mjs from public/favicon.svg.";

/**
 * The window the application opens on: the application's own colour, with the
 * mark centred on it.
 *
 * A layer list rather than the flat picture the template ships, because the mark
 * is what the first screen shows and the two are then the same thing seen twice. The mark is an item
 * of its own so it is centred at its own size and never stretched to the shape
 * of the screen, which a picture scaled to fill would be.
 */
function splashScreenXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${GENERATED} -->`,
    '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">',
    '    <item android:drawable="@color/splash_background" />',
    '    <item',
    '        android:drawable="@drawable/splash_mark"',
    '        android:gravity="center" />',
    '</layer-list>',
    "",
  ].join("\n");
}

/** The colour the launch window is painted in, named so the theme can ask for it. */
function colorsXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${GENERATED} -->`,
    "<resources>",
    `    <color name="splash_background">${BACKGROUND}</color>`,
    "</resources>",
    "",
  ].join("\n");
}

const written = [];
for (const [density, size] of LAUNCHER) {
  written.push({ file: `mipmap-${density}/ic_launcher.png`, png: square(size) });
  written.push({ file: `mipmap-${density}/ic_launcher_round.png`, png: cropped(size) });
}
for (const [density, size] of FOREGROUND) {
  written.push({ file: `mipmap-${density}/ic_launcher_foreground.png`, png: cropped(size) });
}

// The mark on the launch window, once per density, drawn from the same favicon
// as every other piece of artwork here.
for (const [density, size] of SPLASH_MARK) {
  written.push({ file: `drawable-${density}/splash_mark.png`, png: square(size) });
}
written.push({ file: "drawable/splash_screen.xml", text: splashScreenXml() });
written.push({ file: "values/colors.xml", text: colorsXml() });

// The colour an adaptive icon falls back to behind its foreground, written here
// so that the background of an icon is the background of the application.
written.push({
  file: "values/ic_launcher_background.xml",
  text: `<resources>\n    <color name="ic_launcher_background">${BACKGROUND}</color>\n</resources>\n`,
});

// The flat splash files the template ships are gone: a colour with nothing on it,
// which the layer list above replaces. One left behind is a drawable nobody
// references, so it is removed here and its return refused in check mode, where
// the difference between what is on disk and what the favicon draws is what the
// command reports.
const leftoverSplash = [];
for (const directory of readdirSync(RES).filter((name) => name.startsWith("drawable"))) {
  const legacy = path.join(RES, directory, "splash.png");
  if (!existsSync(legacy)) continue;
  leftoverSplash.push(`${directory}/splash.png`);
  if (!check) unlinkSync(legacy);
}

let stale = 0;
for (const { file, png, text } of written) {
  const target = path.join(RES, file);
  const body = png ?? Buffer.from(text, "utf8");
  const current = existsSync(target) ? readFileSync(target) : null;
  if (check) {
    if (!current || !current.equals(body)) {
      console.error(`android-icons: ${file} is out of date`);
      stale += 1;
    }
    continue;
  }
  // The mark on the launch window lives in density directories the template did
  // not have, since its splash was one picture per orientation: they are made
  // here rather than committed empty, which git could not carry anyway.
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, body);
}

if (check) {
  for (const file of leftoverSplash) {
    console.error(`android-icons: ${file} is the template's flat splash, which nothing references any more`);
  }
}

if (check && (stale > 0 || leftoverSplash.length > 0)) {
  console.error(
    `android-icons: ${stale + leftoverSplash.length} file(s) no longer match the favicon. Run npm run android:icons.`
  );
  process.exit(1);
}
if (check) console.log(`android-icons: ${written.length} file(s) match the favicon`);
else console.log(`android-icons: wrote ${written.length} file(s) into android/ from the favicon`);
